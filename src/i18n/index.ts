export type TranslationKey = keyof (typeof messages)["en"];

export function resolveLocale(
  preference: LanguagePreference,
  browserLocales?: readonly string[],
): ResolvedLocale {
  if (preference !== "system") return preference;
  const locales = browserLocales?.length ? browserLocales : ["en"];
  return locales.some(
    (locale) => locale.toLowerCase() === "pt" || locale.toLowerCase().startsWith("pt-"),
  )
    ? "pt-BR"
    : "en";
}

export function translate(
  locale: ResolvedLocale,
  key: TranslationKey,
  params?: Record<string, string | number>,
) {
  const selected = messages[locale] ?? messages.en;
  let value: string = selected[key] ?? messages.en[key];
  if (!value) return `[missing:${String(key)}]`;
  for (const [name, replacement] of Object.entries(params ?? {})) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}
